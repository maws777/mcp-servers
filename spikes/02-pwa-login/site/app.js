// Spike 2: does an iPhone home-screen PWA get through Cognito's login and
// back into the installed app, and stay signed in?
//
// The classic iOS pitfall: a standalone PWA that navigates to another domain
// (the Cognito login page) shows it in an overlay. When Cognito redirects
// back to our site, older iOS versions sometimes finished in Safari instead
// of the app, and Safari doesn't share storage with the home-screen app, so
// the PKCE verifier was gone and the login failed. This page logs the display
// mode at every step to see where each step happens.
//
// Flow: authorization code + PKCE, public client (no secret), straight from
// the browser to Cognito's /oauth2/authorize and /oauth2/token.

"use strict";

const cfg = window.SPIKE_CONFIG; // config.js, generated by Terraform
const KEYS = { log: "spike2.log", pkce: "spike2.pkce", tokens: "spike2.tokens" };

// --- small helpers ----------------------------------------------------------

function displayMode() {
  if (window.matchMedia("(display-mode: standalone)").matches || navigator.standalone === true) return "standalone";
  return "browser";
}

function load(key) {
  try { return JSON.parse(localStorage.getItem(key) || "null"); } catch { return null; }
}
function save(key, value) {
  try { localStorage.setItem(key, JSON.stringify(value)); } catch (e) { addLog("localStorage write failed: " + e.message, true); }
}

function addLog(message, isError = false) {
  const entries = load(KEYS.log) || [];
  entries.push({ t: new Date().toLocaleTimeString("fr-FR"), mode: displayMode(), message, isError });
  save(KEYS.log, entries.slice(-50));
  renderLog();
}

function base64url(bytes) {
  let s = "";
  for (const b of new Uint8Array(bytes)) s += String.fromCharCode(b);
  return btoa(s).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
}
function randomString(n) {
  return base64url(crypto.getRandomValues(new Uint8Array(n)));
}
function decodeJwt(token) {
  const part = token.split(".")[1].replace(/-/g, "+").replace(/_/g, "/");
  return JSON.parse(atob(part));
}

async function tokenRequest(params) {
  const res = await fetch(`${cfg.loginBaseUrl}/oauth2/token`, {
    method: "POST",
    headers: { "content-type": "application/x-www-form-urlencoded" },
    body: new URLSearchParams({ client_id: cfg.clientId, ...params }),
  });
  const body = await res.json().catch(() => ({}));
  if (!res.ok) throw new Error(`${res.status} ${body.error || ""} ${body.error_description || ""}`.trim());
  return body;
}

// --- the flow ---------------------------------------------------------------

async function login() {
  // PKCE: a random secret (verifier) kept here, and its SHA-256 (challenge)
  // sent to Cognito. Only whoever holds the verifier can redeem the code.
  const verifier = randomString(64);
  const challenge = base64url(await crypto.subtle.digest("SHA-256", new TextEncoder().encode(verifier)));
  const state = randomString(16); // ties the callback to this login attempt
  save(KEYS.pkce, { verifier, state, startedIn: displayMode() });
  addLog("Départ vers Cognito");

  const url = new URL(`${cfg.loginBaseUrl}/oauth2/authorize`);
  url.search = new URLSearchParams({
    response_type: "code",
    client_id: cfg.clientId,
    redirect_uri: cfg.redirectUri,
    scope: cfg.scope,
    state,
    code_challenge: challenge,
    code_challenge_method: "S256",
  });
  location.assign(url.toString());
}

async function handleCallback() {
  const params = new URLSearchParams(location.search);
  if (!params.has("code") && !params.has("error")) return;
  // Remove the code from the address bar and history right away.
  history.replaceState(null, "", "/");

  if (params.has("error")) {
    addLog(`Retour Cognito avec erreur : ${params.get("error")} ${params.get("error_description") || ""}`, true);
    return;
  }
  addLog("Retour de Cognito avec un code");

  const pkce = load(KEYS.pkce);
  if (!pkce) {
    addLog("Aucun verifier PKCE trouvé : ce contexte ne partage pas le stockage de celui qui a lancé la connexion", true);
    return;
  }
  localStorage.removeItem(KEYS.pkce); // single use
  if (pkce.state !== params.get("state")) {
    addLog("state différent : réponse refusée", true);
    return;
  }
  addLog(`Verifier retrouvé (connexion lancée en mode ${pkce.startedIn})`);

  try {
    const tokens = await tokenRequest({
      grant_type: "authorization_code",
      code: params.get("code"),
      redirect_uri: cfg.redirectUri,
      code_verifier: pkce.verifier,
    });
    save(KEYS.tokens, { access: tokens.access_token, refresh: tokens.refresh_token });
    addLog("Jetons reçus");
  } catch (e) {
    addLog("Échange du code refusé : " + e.message, true);
  }
}

async function refresh(reason) {
  const stored = load(KEYS.tokens);
  if (!stored?.refresh) { addLog("Pas de refresh token", true); return; }
  try {
    const tokens = await tokenRequest({ grant_type: "refresh_token", refresh_token: stored.refresh });
    // With rotation, Cognito returns a new refresh token and the old one is
    // invalidated (after a short grace period).
    const rotated = Boolean(tokens.refresh_token) && tokens.refresh_token !== stored.refresh;
    save(KEYS.tokens, { access: tokens.access_token, refresh: tokens.refresh_token || stored.refresh });
    addLog(`Jeton rafraîchi (${reason}) ; refresh token ${rotated ? "renouvelé (rotation OK)" : "inchangé"}`);
  } catch (e) {
    addLog("Refresh refusé : " + e.message, true);
  }
}

function logout() {
  localStorage.removeItem(KEYS.tokens);
  addLog("Déconnexion");
  const url = new URL(`${cfg.loginBaseUrl}/logout`);
  url.search = new URLSearchParams({ client_id: cfg.clientId, logout_uri: cfg.logoutUri });
  location.assign(url.toString());
}

// --- rendering --------------------------------------------------------------
// Everything goes through textContent, never innerHTML: values from tokens or
// URLs can't inject markup (the habit the real dashboard needs against
// stored XSS).

function renderLog() {
  const list = document.getElementById("log");
  list.replaceChildren();
  for (const e of load(KEYS.log) || []) {
    const li = document.createElement("li");
    li.textContent = `${e.t} [${e.mode}] ${e.message}`;
    if (e.isError) li.className = "err";
    list.appendChild(li);
  }
}

function renderState() {
  const set = (id, v) => (document.getElementById(id).textContent = v);
  set("mode", displayMode());
  const stored = load(KEYS.tokens);
  if (!stored?.access) {
    set("status", "non");
    for (const id of ["sub", "scope", "aud", "exp"]) set(id, "-");
    return;
  }
  const claims = decodeJwt(stored.access);
  const expired = claims.exp * 1000 < Date.now();
  set("status", expired ? "jeton expiré" : "oui");
  set("sub", claims.sub);
  set("scope", claims.scope || "-");
  set("aud", Array.isArray(claims.aud) ? claims.aud.join(" ") : claims.aud || "(absent)");
  set("exp", new Date(claims.exp * 1000).toLocaleString("fr-FR"));
}

async function main() {
  document.getElementById("login").addEventListener("click", login);
  document.getElementById("refresh").addEventListener("click", async () => { await refresh("bouton"); renderState(); });
  document.getElementById("logout").addEventListener("click", logout);
  document.getElementById("clear").addEventListener("click", () => { localStorage.removeItem(KEYS.log); renderLog(); });

  addLog("Page ouverte");
  await handleCallback();

  // Reopening the app hours later: the access token (1 h) has expired, the
  // refresh token (30 days) hasn't. Renewing silently is what "stays signed
  // in" means.
  const stored = load(KEYS.tokens);
  if (stored?.access && decodeJwt(stored.access).exp * 1000 < Date.now() + 60_000) {
    await refresh("ouverture, jeton expiré");
  }
  renderState();
  renderLog();
}

main();
